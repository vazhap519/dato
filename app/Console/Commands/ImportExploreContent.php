<?php

namespace App\Console\Commands;

use App\Models\ExploreContentItem;
use App\Models\ExploreContentPage;
use App\Support\ExploreContent;
use Illuminate\Console\Command;

class ImportExploreContent extends Command
{
    protected $signature = 'explore:import-content {--force : Reset existing edits to original content}';
    protected $description = 'Import all existing self-discovery texts without overwriting edits';

    public function handle(): int
    {
        foreach (ExploreContent::PAGES as $slug => $title) {
            ExploreContentPage::firstOrCreate(['slug' => $slug], ['title' => $title, 'copy' => []]);
        }

        // Generated by npm run build. Fill all visible static texts with their
        // current exact values while keeping previously edited values intact.
        $manifestPath = resource_path('data/explore-copy-manifest.json');
        if (is_file($manifestPath)) {
            $manifest = json_decode((string) file_get_contents($manifestPath), true, 512, JSON_THROW_ON_ERROR);
            foreach (($manifest['pages'] ?? []) as $slug => $entries) {
                if (! isset(ExploreContent::PAGES[$slug])) continue;
                $defaults = [];
                foreach ($entries as $entry) {
                    if (! isset($entry['key']) || ! is_string($entry['text'] ?? null)) continue;
                    $defaults[$entry['key']] = $entry['text'];
                }
                $page = ExploreContentPage::firstOrCreate(
                    ['slug' => $slug],
                    ['title' => ExploreContent::PAGES[$slug], 'copy' => $defaults],
                );
                $existing = $page->copy ?? [];
                $merged = $this->option('force')
                    ? $defaults
                    : array_replace($defaults, $existing);
                if ($merged !== $existing) {
                    $page->copy = $merged;
                    $page->save();
                }
                $this->info('Page texts: '.$slug.' ('.count($defaults).')');
            }
        } else {
            $this->warn('Copy manifest missing. Run npm run build before importing page texts.');
        }

        foreach (ExploreContent::DOCUMENTS as $document => $slug) {
            foreach (ExploreContent::sourceItems($document) as $item) {
                $identity = [
                    'document' => $document,
                    'group_key' => $item['group_key'],
                    'entry_key' => $item['entry_key'],
                ];
                $attributes = [
                    'page_slug' => $slug,
                    'title' => $item['title'],
                    'position' => $item['position'],
                    'payload' => $item['payload'],
                ];
                if ($this->option('force')) {
                    ExploreContentItem::updateOrCreate($identity, $attributes);
                } else {
                    ExploreContentItem::firstOrCreate($identity, $attributes);
                }
            }
            $this->info('Imported ' . $document);
        }

        return self::SUCCESS;
    }
}
