<?php
namespace Database\Seeders;

use App\Models\NumberMeaning;
use Illuminate\Database\Seeder;

class AllNumbersSeeder extends Seeder
{
    /**
     * Compositional, non-predictive interpretations. Existing hand-written
     * entries are never overwritten.
     */
    public function run(): void
    {
        $themes = [
            0 => ['возможностей и паузы', 'открытость', 'пассивное ожидание', 'Где мне полезно сделать паузу?', 'Остановись на минуту и заметь свои ощущения.'],
            1 => ['начала и личного выбора', 'инициативность', 'поспешность', 'Какой шаг я могу выбрать сам?', 'Запиши один посильный шаг.'],
            2 => ['равновесия и диалога', 'чуткость', 'зависимость от одобрения', 'Кого мне важно услышать, включая себя?', 'Выслушай другого, не забывая о своих границах.'],
            3 => ['выражения и творчества', 'искренность', 'рассеянность', 'Что я давно хочу выразить?', 'Запиши мысль без самоцензуры.'],
            4 => ['опоры и структуры', 'последовательность', 'жёсткость', 'Что создаёт мою устойчивость?', 'Наведи порядок в одном небольшом деле.'],
            5 => ['перемен и гибкости', 'любознательность', 'импульсивность', 'Какую перемену я могу принять спокойно?', 'Попробуй привычное действие по-новому.'],
            6 => ['заботы и ответственности', 'внимательность', 'самопожертвование', 'Где мне стоит позаботиться о себе?', 'Выдели несколько минут на собственные потребности.'],
            7 => ['тишины и внутреннего поиска', 'наблюдательность', 'уход от реальности', 'Что я замечаю в тишине?', 'Побудь две минуты без телефона.'],
            8 => ['ресурсов и зрелого действия', 'ответственность', 'стремление к контролю', 'Как я распоряжаюсь своим вниманием?', 'Выбери одно действие, за которое готов отвечать.'],
            9 => ['завершения и отпускания', 'принятие', 'привязанность к прошлому', 'Что я могу завершить без сожаления?', 'Запиши одну вещь, которую готов отпустить.'],
        ];

        for ($n = 1; $n <= 999; $n++) {
            $number = (string) $n;
            if (NumberMeaning::query()->where('number', $number)->exists()) {
                continue;
            }

            $digits = array_map('intval', str_split($number));
            $sum = array_sum($digits);
            while ($sum > 9) {
                $sum = array_sum(array_map('intval', str_split((string) $sum)));
            }
            $theme = $themes[$sum];
            $first = $themes[$digits[0]];
            $last = $themes[end($digits)];

            $symbolism = 'Число ' . $number . ' можно использовать как повод для самонаблюдения. '
                . 'В этой авторской системе его цифры символически соединяют темы '
                . $first[0] . ' и ' . $last[0] . '. '
                . 'Сумма цифр, сведённая к одной (' . $sum . '), добавляет тему '
                . $theme[0] . '. Это метафора для размышления, а не предсказание событий.';

            NumberMeaning::query()->create([
                'number' => $number,
                'title' => 'Внимание к теме ' . $theme[0],
                'symbolism' => $symbolism,
                'light_side' => 'Обрати внимание на ' . $theme[1] . ' и на то, как это качество проявляется в твоей жизни.',
                'shadow_side' => 'Возможная тема для исследования — ' . $theme[2] . '. Это не диагноз и не утверждение о твоём характере.',
                'reflection_question' => $theme[3],
                'practice' => $theme[4],
                'is_published' => true,
            ]);
        }
    }
}
